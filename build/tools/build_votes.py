#!/usr/bin/env python3
"""Build the full roll-call index (YAML) and monthly summary from the Voteview dataset.

Usage: python3 build/tools/build_votes.py <first_congress> <last_congress> <outdir> [rollcalls.csv|-] [keyword regex]
With a keyword regex only roll calls whose description, question or bill matches are kept (the regex is the selection rule; log it).
Source: https://voteview.com/static/data/out/rollcalls/HSall_rollcalls.csv (secondary dataset; each row links to the
official House Clerk or Senate.gov XML through URL templates in the file header). Deterministic: same input, same output.
"""
import csv, sys, os, re, hashlib, urllib.request, collections, yaml

URL = "https://voteview.com/static/data/out/rollcalls/HSall_rollcalls.csv"
first, last, out = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]
src = sys.argv[4] if len(sys.argv) > 4 and sys.argv[4] != "-" else None
keywords = re.compile(sys.argv[5], re.I) if len(sys.argv) > 5 else None
os.makedirs(out, exist_ok=True)
if not src:
    src = os.path.join(out, "_HSall_rollcalls.csv")
    req = urllib.request.Request(URL, headers={"User-Agent": "Mozilla/5.0"})
    open(src, "wb").write(urllib.request.urlopen(req, timeout=120).read())
sha = hashlib.sha256(open(src, "rb").read()).hexdigest()
rows = [r for r in csv.DictReader(open(src, encoding="utf-8")) if first <= int(r["congress"]) <= last]
if keywords: rows = [r for r in rows if keywords.search(" ".join([r["vote_desc"], r["dtl_desc"], r["vote_question"], r["bill_number"]]))]

def num(x):
    try: return int(float(x))
    except Exception: return 0

BILL = re.compile(r"^(HR|S|HJRE|SJRE)\d+$")
def category(r):
    q = (r["vote_question"] + " " + r["vote_result"]).lower()
    if BILL.match(r["bill_number"] or "") and ("passage" in q or "and pass" in q): return "passage"
    if "nomination" in q or "confirm" in q: return "nomination"
    if "cloture" in q: return "cloture"
    if "amend" in q: return "amendment"
    return "other"

def official_url(r):
    if int(r["date"][:4]) < 1990:   # no official XML before 1990: link the Voteview page for the roll call (secondary)
        return "https://voteview.com/rollcall/R%s%03d%04d" % (r["chamber"][0], int(r["congress"]), num(r["rollnumber"]))
    if r["chamber"] == "House":
        y = r["date"][:4]; return f"https://clerk.house.gov/evs/{y}/roll{num(r['clerk_rollnumber']):03d}.xml"
    c, s = r["congress"], r["session"]
    return f"https://www.senate.gov/legislative/LIS/roll_call_votes/vote{c}{s}/vote_{c}_{s}_{num(r['clerk_rollnumber']):05d}.xml"

def esc(s): return (s or "").replace('"', "'").replace("\\", "").strip()
by_cong = collections.defaultdict(list)
for r in rows: by_cong[int(r["congress"])].append(r)
for c, rs in sorted(by_cong.items()):
    rs.sort(key=lambda r: (r["date"], r["chamber"], num(r["rollnumber"])))
    with open(os.path.join(out, f"rollcalls-{c}.yaml"), "w") as f:
        f.write(f"# Roll-call index, {c}th Congress. GENERATED by build/tools/build_votes.py. Do not edit by hand.\n")
        f.write(f"# Source: Voteview HSall_rollcalls.csv (sha256 {sha}); secondary dataset.\n")
        f.write("# Official record per row: House https://clerk.house.gov/evs/<year>/roll<clerk number, 3 digits>.xml ;\n")
        f.write("#   Senate https://www.senate.gov/legislative/LIS/roll_call_votes/vote<congress><session>/vote_<congress>_<session>_<number, 5 digits>.xml\n")
        f.write("# Fields: ch H|S, s session of the Congress (1 or 2), n roll number as the chamber's own record numbers it (House: per year; Senate: per session), d date, b bill, q question, t description,\n")
        f.write("#   res result, y yea, x nay, k category (passage|nomination|cloture|amendment|other)\n")
        f.write(f"congress: {c}\nrollcalls:\n")
        for r in rs:
            n = num(r["clerk_rollnumber"]) if int(r["date"][:4]) >= 1990 else num(r["rollnumber"])
            f.write('  - {ch: %s, s: %s, n: %d, d: %s, b: "%s", q: "%s", t: "%s", res: "%s", y: %d, x: %d, k: %s}\n' % (
                r["chamber"][0], r["session"], n, r["date"], esc(r["bill_number"]), esc(r["vote_question"]), esc(r["vote_desc"] or r["dtl_desc"])[:140],
                esc(r["vote_result"]), num(r["yea_count"]), num(r["nay_count"]), category(r)))

# monthly summary + closest passage votes
months = collections.defaultdict(lambda: collections.Counter())
for r in rows:
    months[r["date"][:7]][(r["chamber"][0], category(r))] += 1
closest = []
for c, rs in sorted(by_cong.items()):
    for ch in ("House", "Senate"):
        cand = [r for r in rs if r["chamber"] == ch and category(r) == "passage" and num(r["yea_count"]) + num(r["nay_count"]) >= 50]
        cand.sort(key=lambda r: (abs(num(r["yea_count"]) - num(r["nay_count"])), r["date"], num(r["rollnumber"])))
        for r in cand[:3]:
            closest.append({"congress": c, "chamber": ch[0], "date": r["date"], "bill": r["bill_number"], "question": r["vote_question"],
                            "description": (r["vote_desc"] or r["dtl_desc"])[:140], "result": r["vote_result"], "yea": num(r["yea_count"]),
                            "nay": num(r["nay_count"]), "url": official_url(r)})
summary = {"generated_by": "build/tools/build_votes.py", "source_sha256": sha, "rolls": len(rows),
           "closest_rule": "For each Congress and chamber, the 3 passage votes of bills or joint resolutions with the smallest |yea - nay| (at least 50 votes cast); ties by earlier date. Not a judgement of importance.",
           "months": {m: {f"{k[0]}_{k[1]}": v for k, v in sorted(c.items())} for m, c in sorted(months.items())},
           "closest_passage": closest}
yaml.safe_dump(summary, open(os.path.join(out, "summary.yaml"), "w"), sort_keys=False, width=140)
print(len(rows), "rolls;", len(by_cong), "congresses; sha256", sha[:12])
